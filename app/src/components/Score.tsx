import { useEffect, useMemo, useRef } from "react";

import type { Mark } from "../bridge";

/** How a note is being shown, if it is being shown at all. */
export type NoteState = "cursor" | "correct" | "wrong";

/** Which notes are marked, keyed by position in the piece. */
export type Marked = ReadonlyMap<number, NoteState>;

const CLASS_FOR: Record<NoteState, string> = {
  cursor: "hw-cursor",
  correct: "hw-correct",
  wrong: "hw-wrong",
};

const EVERY_CLASS = Object.values(CLASS_FOR);

/**
 * The engraved score, with notes marked on it.
 *
 * # Why the SVG is not React's business
 *
 * A page of engraving is a few thousand elements. Rendering it through React
 * would put all of them through reconciliation every time one note changed —
 * ten times a second while someone is playing — for a change that is one
 * attribute on one element.
 *
 * So the markup is injected once, imperatively, and afterwards this component
 * only ever adds and removes classes through `getElementById`. React owns the
 * panel; it does not own what is inside it. That is a deliberate exception to
 * how the rest of the interface is built, and it is confined to this file.
 *
 * # Why there are no coordinates here
 *
 * Because the browser has them. `ADR-0012` records what the previous approach
 * cost: rasterising the score meant asking a geometry library for each
 * notehead's bounding box, and that library reported them in the wrong place
 * for every glyph drawn with `<use>` — which is every notehead. Here a note is
 * an element, and marking it is a class.
 */
export function Score({
  pages,
  marks,
  marked,
  followCursor = true,
}: {
  readonly pages: readonly string[];
  readonly marks: readonly Mark[];
  readonly marked: Marked;
  readonly followCursor?: boolean;
}) {
  const container = useRef<HTMLDivElement>(null);
  const applied = useRef<Marked>(new Map());

  /** Position in the piece → the elements drawn for it. */
  const elementsAt = useMemo(() => {
    const index = new Map<number, readonly string[]>();

    for (const mark of marks) {
      index.set(mark.position, mark.elementIds);
    }

    return index;
  }, [marks]);

  // The pages, injected once per piece. `marks` deliberately is not a
  // dependency: new marks for the same score must not re-inject it.
  useEffect(() => {
    const panel = container.current;
    if (!panel) return;

    panel.replaceChildren();

    for (const page of pages) {
      const holder = document.createElement("div");
      holder.className = "hw-page";
      // Sanitised before it reaches the DOM. Verovio generates this markup
      // rather than copying it, so the risk is low — but it derives from a
      // file the performer chose, and stripping scripts costs nothing.
      holder.innerHTML = sanitise(page);
      panel.append(holder);
    }

    applied.current = new Map();
  }, [pages]);

  // Only what changed. Comparing against the previous state means a frame in
  // which nothing moved touches no elements at all.
  useEffect(() => {
    const panel = container.current;
    if (!panel) return;

    const previous = applied.current;

    for (const [position, was] of previous) {
      if (marked.get(position) !== was) {
        setState(panel, elementsAt.get(position), null);
      }
    }

    for (const [position, now] of marked) {
      if (previous.get(position) !== now) {
        setState(panel, elementsAt.get(position), now);
      }
    }

    applied.current = new Map(marked);
  }, [marked, elementsAt]);

  // Keep the cursor in view. `block: "center"` rather than "nearest" so the
  // performer reads with music above and below, not pinned to an edge.
  useEffect(() => {
    if (!followCursor) return;

    const panel = container.current;
    if (!panel) return;

    for (const [position, state] of marked) {
      if (state !== "cursor") continue;

      const first = elementsAt.get(position)?.[0];
      const element = first ? panel.querySelector(`#${CSS.escape(first)}`) : null;

      element?.scrollIntoView({ behavior: "smooth", block: "center" });
      return;
    }
  }, [marked, elementsAt, followCursor]);

  return <div ref={container} className="mx-auto max-w-4xl" />;
}

/** Puts `state` on every element drawn for one position, or clears them. */
function setState(
  panel: HTMLElement,
  ids: readonly string[] | undefined,
  state: NoteState | null,
): void {
  if (!ids) return;

  for (const id of ids) {
    const element = panel.querySelector(`#${CSS.escape(id)}`);
    if (!element) continue;

    element.classList.remove(...EVERY_CLASS);
    if (state) element.classList.add(CLASS_FOR[state]);
  }
}

/**
 * Removes anything executable from engraver output.
 *
 * SVG can carry `<script>` and `on*` handlers, and this markup — though
 * generated by Verovio rather than copied from the source — ultimately
 * derives from a file the performer supplied. The application's CSP already
 * refuses inline script, so this is the second of two locks rather than the
 * only one.
 */
function sanitise(svg: string): string {
  const parsed = new DOMParser().parseFromString(svg, "image/svg+xml");

  for (const script of parsed.querySelectorAll("script")) {
    script.remove();
  }

  for (const element of parsed.querySelectorAll("*")) {
    for (const attribute of [...element.attributes]) {
      const name = attribute.name.toLowerCase();

      if (name.startsWith("on") || (name === "href" && attribute.value.trim().toLowerCase().startsWith("javascript:"))) {
        element.removeAttribute(attribute.name);
      }
    }
  }

  return new XMLSerializer().serializeToString(parsed);
}
